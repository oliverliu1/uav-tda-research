"""Manuscript numbers: LaTeX macros generated from committed rebuild CSVs."""
import json
import re

import pytest

from uav_tda import cli
from uav_tda import manuscript_numbers as mn
from uav_tda.paths import TABLES_DIR

REBUILD = TABLES_DIR / "rebuild"


def _rebuild(tmp_path):
    rebuild = tmp_path / "results" / "tables" / "rebuild"
    (rebuild / "exact").mkdir(parents=True)
    (rebuild / "exact" / "t.csv").write_text(
        "subset,scoring,auc,n_flows,w\n"
        "all_three,znorm,0.9082,18326,\n"
        "all_three,raw,0.9037,18326,\n"
        "net,znorm,0.7533,18326,25.0\n"
    )
    return rebuild


def test_emit_is_one_newcommand_per_number_with_its_source(tmp_path):
    spec = [
        mn.Num("AucAll", "exact/t.csv", {"subset": "all_three", "scoring": "znorm"}, "auc"),
        mn.Num("NFlows", "exact/t.csv", {"subset": "all_three", "scoring": "raw"}, "n_flows",
               fmt=",.0f"),
    ]
    text = mn.render_numbers(_rebuild(tmp_path), spec)
    lines = text.splitlines()
    assert lines[0].startswith("% Generated by `uav-tda manuscript-numbers`")
    assert (r"\newcommand{\AucAll}{0.91}% exact/t.csv: subset=all_three, scoring=znorm -> auc"
            in lines)
    assert (r"\newcommand{\NFlows}{18{,}326}% exact/t.csv: subset=all_three, scoring=raw "
            "-> n_flows" in lines)
    assert text.endswith("\n")


def test_ratio_scale_and_missing_value_selectors(tmp_path):
    rebuild = _rebuild(tmp_path)
    ratio = mn.Num("Share", "exact/t.csv", {"subset": "net"}, "auc", fmt=".0f", scale=100.0,
                   over=({"subset": "all_three", "scoring": "znorm"}, "auc"))
    assert mn.resolve(rebuild, ratio) == "83"
    # None selects the row whose cell is empty; a number selects numerically.
    blank = mn.Num("A", "exact/t.csv", {"scoring": "znorm", "w": None}, "auc")
    assert mn.resolve(rebuild, blank) == "0.91"
    by_w = mn.Num("B", "exact/t.csv", {"w": 25}, "auc")
    assert mn.resolve(rebuild, by_w) == "0.75"
    # "sig3": three significant figures, no exponent form.
    for scale, want in ((1.0, "0.753"), (10.0, "7.53"), (1341.0, "1{,}010")):
        ms = mn.Num("C", "exact/t.csv", {"w": 25}, "auc", fmt="sig3", scale=scale)
        assert mn.resolve(rebuild, ms) == want


def test_a_selector_must_match_exactly_one_row(tmp_path):
    rebuild = _rebuild(tmp_path)
    with pytest.raises(ValueError, match="Many.*2 rows"):
        mn.resolve(rebuild, mn.Num("Many", "exact/t.csv", {"subset": "all_three"}, "auc"))
    with pytest.raises(ValueError, match="Zero.*0 rows"):
        mn.resolve(rebuild, mn.Num("Zero", "exact/t.csv", {"subset": "nope"}, "auc"))


def test_macro_names_must_be_letters_and_unique(tmp_path):
    rebuild = _rebuild(tmp_path)
    sel = {"subset": "net"}
    with pytest.raises(ValueError, match="letters"):
        mn.render_numbers(rebuild, [mn.Num("Auc2", "exact/t.csv", sel, "auc")])
    with pytest.raises(ValueError, match="duplicate"):
        mn.render_numbers(rebuild, [mn.Num("A", "exact/t.csv", sel, "auc"),
                                    mn.Num("A", "exact/t.csv", sel, "auc")])


def test_default_spec_resolves_against_committed_csvs():
    values = mn.build_numbers(REBUILD)
    assert list(values) == [n.name for n in mn.NUMBERS]
    # A few pins on signed-off values (prose precision).
    assert values["AucFullAllThree"] == "0.91"
    assert values["AucFullAllThreeBlockLo"] == "0.89"
    assert values["AucFullAllThreeBlockHi"] == "0.93"
    assert values["AucFullNetPhys"] == "0.87"
    assert values["AucProbeAllThree"] == "0.89"
    assert values["AucAttrSybil"] == "0.89"
    assert values["AucWinHundred"] == "0.94"
    assert values["AucWinShufTwentyFive"] == "0.53"
    assert values["LatMacProbe"] == "3.58"
    assert values["LatPiFull"] == "10.55"
    assert values["SpeedupMacWTwentyFive"] == "478"
    assert values["SpeedupPiWTwentyFive"] == "1{,}148"
    assert values["NTestFlows"] == "18{,}326"
    assert values["LatMacWTwentyFiveMs"] == "7.49"
    assert values["LatPiWTwoHundredMs"] == "1{,}010"
    for name, v in values.items():
        assert re.fullmatch(r"[0-9.{},]+", v), (name, v)


def test_committed_numbers_file_matches_a_fresh_render():
    """Changing a CSV without regenerating the manuscript numbers must fail."""
    committed = REBUILD / "paper_snippets" / mn.NUMBERS_FILE
    assert committed.read_text() == mn.render_numbers(REBUILD, mn.NUMBERS)


def test_cli_writes_file_and_sidecar_and_is_idempotent(tmp_path, monkeypatch):
    rebuild = _rebuild(tmp_path)
    monkeypatch.setattr(mn, "NUMBERS", [
        mn.Num("AucAll", "exact/t.csv", {"subset": "all_three", "scoring": "znorm"}, "auc")])
    assert cli.main(["manuscript-numbers", "--root", str(tmp_path)]) == 0
    out = rebuild / "paper_snippets" / mn.NUMBERS_FILE
    side = out.with_name(out.name + ".provenance.json")
    assert r"\newcommand{\AucAll}{0.91}" in out.read_text()
    meta = json.loads(side.read_text())
    assert meta["params"]["n_numbers"] == 1 and "artifact_sha256" in meta
    before = (out.read_bytes(), side.read_bytes())
    assert cli.main(["manuscript-numbers", "--root", str(tmp_path)]) == 0
    assert (out.read_bytes(), side.read_bytes()) == before


def test_unchanged_numbers_leave_the_sidecar_alone_at_a_new_commit(tmp_path, monkeypatch):
    """Rebuilding the manuscript must not dirty the repo when no number changed."""
    from uav_tda import provenance

    rebuild = _rebuild(tmp_path)
    monkeypatch.setattr(mn, "NUMBERS", [
        mn.Num("AucAll", "exact/t.csv", {"subset": "all_three", "scoring": "znorm"}, "auc")])
    monkeypatch.setattr(provenance, "_git_sha", lambda: "a" * 40)
    out = mn.write_numbers(tmp_path)
    side = out.with_name(out.name + ".provenance.json")
    before = side.read_bytes()
    monkeypatch.setattr(provenance, "_git_sha", lambda: "b" * 40)
    mn.write_numbers(tmp_path)
    assert side.read_bytes() == before
    # A changed number does update both files.
    (rebuild / "exact" / "t.csv").write_text(
        "subset,scoring,auc,n_flows,w\nall_three,znorm,0.5,1,\n")
    mn.write_numbers(tmp_path)
    assert "{0.50}" in out.read_text() and json.loads(side.read_text())["git_sha"] == "b" * 40
