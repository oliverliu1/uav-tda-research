"""Manuscript numbers: every number cited in the manuscript's running text, as LaTeX macros.

`uav-tda manuscript-numbers` reads committed CSVs under `results/tables/rebuild/` and
writes `paper_snippets/manuscript_numbers.tex`: one ``\\newcommand`` per number, each with
a trailing comment naming its CSV, row and column. The manuscript ``\\input``s that file and
writes ``\\AucFullAllThree{}`` instead of a typed digit, so no number in the prose is
hand-copied. Nothing is recomputed here; a value is one CSV cell (optionally divided by
another cell of the same file, and scaled), formatted.

Prose precision follows the project brief: two decimals for AUCs. Tables that carry four
decimals come from the row snippets, not from this file.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

import pandas as pd

from . import config
from .paths import REPO_ROOT
from .provenance import write_provenance

NUMBERS_FILE = "manuscript_numbers.tex"


@dataclass(frozen=True)
class Num:
    """One cited number: ``name`` is the macro, the rest says where its value lives.

    ``where`` maps column -> value and must select exactly one row (``None`` selects an
    empty cell). ``over`` = (where, col) divides by another cell of the same CSV.
    """

    name: str
    csv: str
    where: dict
    col: str
    fmt: str = ".2f"
    scale: float = 1.0
    over: Optional[tuple] = field(default=None)


def _cell(df: pd.DataFrame, where: dict, col: str, num: Num) -> float:
    sel = pd.Series(True, index=df.index)
    for key, want in where.items():
        if want is None:
            sel &= df[key].isna()
        elif isinstance(want, (int, float)) and not isinstance(want, bool):
            sel &= pd.to_numeric(df[key], errors="coerce") == float(want)
        else:
            sel &= df[key] == want
    hit = df[sel]
    if len(hit) != 1:
        raise ValueError(f"manuscript number {num.name}: {num.csv} {where} matched "
                         f"{len(hit)} rows, expected 1")
    return float(hit.iloc[0][col])


def resolve(rebuild_dir, num: Num, _cache: Optional[dict] = None) -> str:
    """The formatted value of one number (thousands separators as ``{,}`` for LaTeX)."""
    cache = {} if _cache is None else _cache
    if num.csv not in cache:
        path = Path(rebuild_dir) / num.csv
        if path.suffix == ".json":  # a flat JSON object is read as one row
            cache[num.csv] = pd.DataFrame([json.loads(path.read_text())])
        else:
            cache[num.csv] = pd.read_csv(path, float_precision="round_trip")
    df = cache[num.csv]
    value = _cell(df, num.where, num.col, num)
    if num.over is not None:
        value /= _cell(df, num.over[0], num.over[1], num)
    value *= num.scale
    if num.fmt == "sig3":  # three significant figures, never in exponent form
        text = format(float(f"{value:.3g}"), ",.10g")
    else:
        text = format(value, num.fmt)
    return text.replace(",", "{,}")


def _source(num: Num) -> str:
    def sel(where):
        return ", ".join(f"{k}={'' if v is None else v}" for k, v in where.items())

    text = f"{num.csv}: {sel(num.where)} -> {num.col}"
    if num.over is not None:
        text += f" / ({sel(num.over[0])} -> {num.over[1]})"
    if num.scale != 1.0:
        text += f" x {num.scale:g}"
    return text


def _check_names(spec) -> None:
    seen = set()
    for num in spec:
        if not re.fullmatch(r"[A-Za-z]+", num.name):
            raise ValueError(f"manuscript number {num.name!r}: a LaTeX macro name is letters only")
        if num.name in seen:
            raise ValueError(f"manuscript number {num.name!r}: duplicate name")
        seen.add(num.name)


def build_numbers(rebuild_dir=None, spec=None) -> dict:
    """``{macro name: formatted value}`` in spec order."""
    rebuild = Path(rebuild_dir) if rebuild_dir is not None else _default_rebuild()
    spec = NUMBERS if spec is None else spec
    _check_names(spec)
    cache: dict = {}
    return {num.name: resolve(rebuild, num, cache) for num in spec}


def render_numbers(rebuild_dir=None, spec=None) -> str:
    """The text of `manuscript_numbers.tex`."""
    spec = NUMBERS if spec is None else spec
    values = build_numbers(rebuild_dir, spec)
    lines = [
        "% Generated by `uav-tda manuscript-numbers` from results/tables/rebuild/; "
        "do not edit by hand.",
        "% Use as \\Name{} in running text. Each line ends with the CSV cell it came from.",
    ]
    lines += [f"\\newcommand{{\\{num.name}}}{{{values[num.name]}}}% {_source(num)}"
              for num in spec]
    return "\n".join(lines) + "\n"


def write_numbers(root=None) -> Path:
    """Write the numbers file and its sidecar under workspace ``root`` (default: the repo)."""
    root = Path(root) if root is not None else REPO_ROOT
    rebuild = root / "results" / "tables" / "rebuild"
    path = rebuild / "paper_snippets" / NUMBERS_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    text = render_numbers(rebuild, NUMBERS)
    side = path.with_name(path.name + ".provenance.json")
    if path.exists() and side.exists() and path.read_text() == text:
        return path  # nothing changed: keep the sidecar of the commit that last changed it
    path.write_text(text)
    write_provenance(path, {"builder": "manuscript_numbers.render_numbers",
                            "n_numbers": len(NUMBERS),
                            "sources": sorted({n.csv for n in NUMBERS})},
                     skip_if_unchanged=True)
    return path


def _default_rebuild() -> Path:
    return REPO_ROOT / "results" / "tables" / "rebuild"


# ---------------------------------------------------------------------------
# The numbers. Names are letters only (LaTeX): Conn = C2, Net = Network, Phys = Physical;
# window sizes are spelled out. "Full" = full test split at delta<=0.01; "Probe" = ten-seed
# probe; "Win" = time-windowed, ordered arm, z-norm, all three manifolds.
# ---------------------------------------------------------------------------

_W = {25: "TwentyFive", 50: "Fifty", 100: "Hundred", 200: "TwoHundred"}
_MAC, _PI = config.LATENCY_PRIMARY_HOST, "uav-pi5"
_ATTACKS = {"Sybil": "Sybil Attack", "Flooding": "Flooding Attack",
            "Blackhole": "Blackhole Attack", "Wormhole": "Wormhole Attack"}
_SUBSETS = {"AllThree": "all_three", "NetPhys": "network_physical", "ConnNet": "c2_network",
            "ConnPhys": "c2_physical", "Conn": "c2_only", "Net": "network_only",
            "Phys": "physical_only"}


def _spec() -> list:
    out = []
    exact, dep = "exact/exact_binary_auc.csv", "exact/flow_dependence.csv"
    top = {"subset": "all_three", "scoring": "znorm"}

    # Methodology: data-derived constants.
    caps, op_csv = "artifacts/max_edge_lengths.json", "artifacts/operating_points.csv"
    for tag, key in (("Conn", "c2"), ("Net", "network"), ("Phys", "physical")):
        out.append(Num(f"EpsMax{tag}", caps, {}, key, fmt=".3f"))
    for name, col in (("NValNormal", "n_val_normal"), ("NTestNormal", "n_test_normal"),
                      ("NTestAttack", "n_test_attack")):
        out.append(Num(name, op_csv, top, col, fmt=",.0f"))
    for w, tag in _W.items():
        out.append(Num(f"NWin{tag}", "artifacts/unique_window_counts.csv", {"w": w},
                       "n_windows", fmt=",.0f"))

    # Per-flow detection, full test split.
    for tag, subset in _SUBSETS.items():
        out.append(Num(f"AucFull{tag}", exact, {"subset": subset, "scoring": "znorm"}, "auc"))
    out += [
        Num("AucFullAllThreeRaw", exact, {"subset": "all_three", "scoring": "raw"}, "auc"),
        Num("AucFullAllThreeIidLo", exact, top, "ci_lo"),
        Num("AucFullAllThreeIidHi", exact, top, "ci_hi"),
        Num("AucFullAllThreeBlockLo", dep, {"block_len": 250}, "ci_lo"),
        Num("AucFullAllThreeBlockHi", dep, {"block_len": 250}, "ci_hi"),
        Num("FlowLagOne", dep, {"block_len": 1}, "lag1_autocorr"),
        Num("NTestFlows", exact, top, "n_flows", fmt=",.0f"),
    ]

    # Ten-seed probe (sampling-stability study).
    probe = "binary_auc.csv"
    for tag in ("AllThree", "NetPhys"):
        sel = {"subset": _SUBSETS[tag], "scoring": "znorm"}
        out += [Num(f"AucProbe{tag}", probe, sel, "mean"),
                Num(f"AucProbe{tag}Std", probe, sel, "std")]

    # Per-flow attribution, full test split (dominant manifold per attack).
    per_attack = "exact/exact_per_attack_auc.csv"
    for tag, attack in _ATTACKS.items():
        out.append(Num(f"AucAttr{tag}", per_attack,
                       {"attack_class": attack, "dominant": True}, "auc"))

    # Operating point at the validation-Normal 95th percentile.
    op = "artifacts/operating_points.csv"
    out += [Num("OpFprPct", op, top, "fpr", fmt=".1f", scale=100.0), Num("OpTpr", op, top, "tpr")]
    for tag in _ATTACKS:
        out.append(Num(f"OpTpr{tag}", op, top, f"tpr_{tag.lower()}"))

    # Time-windowed variant.
    det, wdep = "windowed/windowed_detection.csv", "windowed/window_dependence.csv"
    attr = "windowed/windowed_attribution.csv"
    for w, tag in _W.items():
        ordered = {"w": w, "arm": "ordered", **top}
        out += [
            Num(f"AucWin{tag}", det, ordered, "mean"),
            Num(f"AucWin{tag}Lo", det, ordered, "ci_lo"),
            Num(f"AucWin{tag}Hi", det, ordered, "ci_hi"),
            Num(f"AucWin{tag}BlockLo", wdep, {"w": w, "block_len": config.REPORT_BLOCK_LEN},
                "ci_lo"),
            Num(f"AucWin{tag}BlockHi", wdep, {"w": w, "block_len": config.REPORT_BLOCK_LEN},
                "ci_hi"),
            Num(f"AucWinShuf{tag}", det, {"w": w, "arm": "shuffled", **top}, "mean"),
            Num(f"AucWinSybilConn{tag}", attr,
                {"w": w, "attack_class": "Sybil Attack", "manifold": "c2"}, "mean"),
        ]

    # Latency, per decision, by host.
    lat = "artifacts/latency_by_host.csv"
    for host_tag, host in (("Mac", _MAC), ("Pi", _PI)):
        for mode_tag, mode in (("Probe", "per_flow"), ("Full", "per_flow_exact")):
            sel = {"host": host, "mode": mode}
            out += [Num(f"Lat{host_tag}{mode_tag}", lat, sel, "mean_s"),
                    Num(f"Lat{host_tag}{mode_tag}PNinetyFive", lat, sel, "p95_s")]
        for w, tag in _W.items():
            sel = {"host": host, "mode": "windowed", "w": w}
            out += [Num(f"Lat{host_tag}W{tag}Ms", lat, sel, "mean_s", fmt="sig3", scale=1000.0),
                    Num(f"Speedup{host_tag}W{tag}", lat, sel, "speedup_vs_per_flow", fmt=",.0f")]
        summary = f"latency_{host}.csv"
        pf = {"mode": "per_flow", "w": None}
        out.append(Num(f"ShareConnRips{host_tag}Pct", summary, {**pf, "stage": "c2_rips_s"},
                       "mean_s", fmt=".0f", scale=100.0,
                       over=({**pf, "stage": "total_s"}, "mean_s")))
    for mode_tag, mode in (("Probe", "per_flow"), ("Full", "per_flow_exact")):
        out.append(Num(f"RatioPiMac{mode_tag}", lat, {"host": _PI, "mode": mode},
                       "ratio_to_primary"))
    return out


NUMBERS = _spec()
